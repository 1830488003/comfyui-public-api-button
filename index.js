    /* 从地址栏取邀请码（?ref=XXX 或 #ref=XXX），存进设置等领取时用 */
    function captureInviteCodeFromUrl() {
        var code = '';
        try {
            var search = new URLSearchParams(window.location.search || '');
            code = search.get('ref') || search.get('invite') || '';
            if (!code && window.location.hash) {
                var hash = new URLSearchParams(String(window.location.hash).replace(/^#/, ''));
                code = hash.get('ref') || hash.get('invite') || '';
            }
        } catch (error) {
            console.warn('[' + extensionName + '] 解析邀请码失败', error);
            code = '';
        }
        code = normalizeInviteCode(code);
        if (code) {
            settings.pendingInviteCode = code;
            saveSettings();
            $('#cpab-invite-input').val(code);
        }
        return code;
    }

