    function parseManifestVersion(content) {
        try {
            return String(JSON.parse(content).version || '0.0.0').trim();
        } catch (error) {
            throw new Error('版本文件格式错误');
        }
    }

    function compareVersions(left, right) {
        var leftParts = String(left || '0.0.0').replace(/^v/i, '').split('.').map(Number);
        var rightParts = String(right || '0.0.0').replace(/^v/i, '').split('.').map(Number);
        var length = Math.max(leftParts.length, rightParts.length);
        for (var index = 0; index < length; index++) {
            var leftValue = Number.isFinite(leftParts[index]) ? leftParts[index] : 0;
            var rightValue = Number.isFinite(rightParts[index]) ? rightParts[index] : 0;
            if (leftValue > rightValue) return 1;
            if (leftValue < rightValue) return -1;
        }
        return 0;
    }

    /* 从多个源读取版本文件，取版本号最高的那个。
       为什么要多个源：GitHub 的 raw CDN 会按 URL 路径缓存，推送新版本后
       .../main/manifest.json 可能长时间仍返回旧内容（实测遇到过一直返回上一个
       版本、X-Cache: HIT 的情况），导致「检查更新」永远发现不了新版本。
       /refs/heads/main/ 与 jsDelivr 走的是不同的缓存，通常能立刻拿到最新内容。
       任何一个源成功即可，全部失败才报错。 */
    function updaterSources(filePath) {
        var repo = updaterRepoOwner + '/' + updaterRepoName;
        var bust = '?t=' + Date.now();
        return [
            'https://raw.githubusercontent.com/' + repo + '/refs/heads/main/' + filePath + bust,
            'https://cdn.jsdelivr.net/gh/' + repo + '@main/' + filePath + bust,
            'https://raw.githubusercontent.com/' + repo + '/main/' + filePath + bust
        ];
    }

    /* 从所有源里读出每个能拿到的版本号。
       注意：不能"第一个能解析就用"——GitHub raw 和 jsDelivr 都可能返回**缓存里的旧版本**
       （实测 jsDelivr 缓存过 11 小时以上），那样会误报"已是最新"，用户就更新不了。
       所以要把所有源都读一遍，再挑版本号最大的。 */
    async function collectRemoteManifestVersions() {
        var sources = updaterSources('manifest.json');
        var found = [];
        var lastError = null;
        for (var i = 0; i < sources.length; i++) {
            try {
                var response = await fetch(sources[i], { cache: 'no-store' });
                if (!response.ok) { lastError = new Error('HTTP ' + response.status); continue; }
                var content = await response.text();
                var version = parseManifestVersion(content);
                if (version) found.push({ version: version, content: content, source: sources[i] });
                else lastError = new Error('版本文件内容不合法');
            } catch (error) {
                lastError = error;
            }
        }
        if (!found.length) throw lastError || new Error('无法读取版本文件，请检查网络');
        return found;
    }

    /* 取所有源里**版本最高**的那个 manifest。
       版本号只会单调递增，所以取最大值一定是对的。 */
    async function fetchLatestRemoteManifest() {
        var found = await collectRemoteManifestVersions();
        var best = found[0];
        for (var i = 1; i < found.length; i++) {
            if (compareVersions(found[i].version, best.version) > 0) best = found[i];
        }
        best.allVersions = found.map(function (x) { return x.version; });
        return best;
    }

    async function fetchRemoteUpdaterFile(filePath) {
        /* 版本文件走"取最高版本"的逻辑，避免被 CDN 缓存骗到 */
        if (filePath === 'manifest.json') {
            return (await fetchLatestRemoteManifest()).content;
        }
        var sources = updaterSources(filePath);
        var lastError = null;
        /* 其他文件按可靠性顺序试，第一个能用的就采用。 */
        for (var i = 0; i < sources.length; i++) {
            try {
                var response = await fetch(sources[i], { cache: 'no-store' });
                if (!response.ok) { lastError = new Error('HTTP ' + response.status); continue; }
                var content = await response.text();
                if (parseManifestVersion(content)) { return content; }
                lastError = new Error('版本文件内容不合法');
            } catch (error) {
                lastError = error;
            }
        }
        throw lastError || new Error('无法读取版本文件，请检查网络');
    }

