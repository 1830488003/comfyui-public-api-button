    function isHighResolution(value) {
        return highResolutions.indexOf(normalizeResolution(value)) >= 0;
    }

    /* 本次生成要花几次额度：高清档 2 次，普通档 1 次。
       与网关的像素判定规则保持一致（超过 512x768 像素总数即高清）。 */
    function creditCostOf(value) {
        return isHighResolution(value) ? HIGH_RES_CREDIT_COST : 1;
    }

    function readGenerationOptions() {
        var resolution = normalizeResolution(settings.resolution);
        var parts = resolution.split('x');
        return {
            width: Number(parts[0]),
            height: Number(parts[1]),
            steps: normalizeSteps(settings.steps),
            resolution: resolution,
            cost: creditCostOf(resolution),
            highRes: isHighResolution(resolution)
        };
    }

    /* 在分辨率下拉下方提示当前档位要花几次，并在按钮标题上同步 */
    function renderResolutionNote() {
        var options = readGenerationOptions();
        var $note = $('#cpab-res-note');
        if ($note.length) {
            if (options.highRes) {
                var remaining = lastKnownQuota && lastKnownQuota.plan_type === 'credits'
                    ? Number(lastKnownQuota.remaining)
                    : null;
                var extra = '';
                if (remaining !== null && Number.isFinite(remaining)) {
                    extra = remaining < options.cost
                        ? '⚠️ 当前仅剩 ' + remaining + ' 次，不足以生成这张高清图。'
                        : '当前剩余 ' + remaining + ' 次，本次将扣 ' + options.cost + ' 次，生成后剩 ' + (remaining - options.cost) + ' 次。';
                }
                $note.removeClass('is-plain').addClass('is-warn').text(
                    '高清档 ' + options.resolution + '：生成慢约 10 秒，每次消耗 ' + options.cost + ' 次额度。' + extra
                );
            } else {
                $note.removeClass('is-warn').addClass('is-plain').text(
                    '普通档 ' + options.resolution + '：每次消耗 ' + options.cost + ' 次额度。'
                );
            }
        }
    }

    function buildGenerationRequest(messageId, mode) {
        var options = readGenerationOptions();
        var last = getGenerationMeta(messageId);
        var payload = { width: options.width, height: options.height, steps: options.steps };
        var actionLabel = '生成图片';
        if (mode === 'random') {
            payload.steps = last && allowedSteps.indexOf(Number(last.steps)) >= 0 ? Number(last.steps) : options.steps;
            actionLabel = '随机重绘';
        }
        if (mode === 'optimize') {
            if (!last) throw new Error('这层还没有历史图片，请先点一次生成图片或随机重绘');
            if (!Number.isFinite(Number(last.seed))) throw new Error('找不到上一次生成的 seed');
            if (!Number.isFinite(Number(last.steps))) throw new Error('找不到上一次生成的步数');
            payload.seed = Number(last.seed);
            payload.steps = Math.min(8, Number(last.steps) + 2);
            actionLabel = '固定 seed 优化（' + last.steps + ' → ' + payload.steps + ' 步）';
        }
        // 把本次要消耗的次数写进按钮提示，高清档会显示「扣 2 次」
        if (options.cost > 1) {
            actionLabel += '｜高清扣 ' + options.cost + ' 次';
        }
        return { payload: payload, actionLabel: actionLabel };
    }

    async function generateForMessage(messageId, $button, mode) {
        var context = contextGetter();
        var message = context && context.chat ? context.chat[messageId] : null;
        if (!message) throw new Error('找不到对应楼层消息');
        var scenePrompt = extractImagePrompt(message.mes);
        var selectedStyle = getStylePreset(settings.stylePreset);
        var selectedStyleUi = getStylePresetUi(selectedStyle.id);
        var prompt = buildStyledPrompt(scenePrompt, selectedStyle.id);
        // 本次实际使用的分辨率与应扣次数（高清档为 2）
        var genOptions = readGenerationOptions();
        var request = buildGenerationRequest(messageId, mode || 'normal');
        request.payload.prompt = prompt;
        setButtonState($button, 'is-loading', request.actionLabel + '中');
        await refreshQueueStatus(true);
        setStatus('楼层 ' + messageId + '：' + request.actionLabel + '，服务器前方 ' + lastQueueAhead + ' 个任务');
        try {
            var data = await apiRequest('/v1/generate', { method: 'POST', body: JSON.stringify(request.payload) });
            setStatus('出图完成，正在保存到酒馆...');
            /* 先压缩再上传：PNG 原图常有 1.5~2.5MB，跨洋隧道传输很慢，
               转成 JPEG 后体积约为原来的 1/5，聊天记录也更清爽。 */
            var packed = await compressForStorage(data.data, data.format || 'png');
            var imageUrl = await uploadImage(packed.data, packed.format);
            var generationMeta = {
                seed: Number(data.seed),
                steps: Number(data.steps),
                prompt: prompt,
                scenePrompt: scenePrompt,
                stylePreset: selectedStyle.id,
                styleName: selectedStyleUi.label,
                styleEnglishName: selectedStyle.name,
                imageUrl: imageUrl,
                savedAt: Date.now()
            };
            await injectImage(messageId, imageUrl, prompt, data.quota, generationMeta);
            if (data.quota) { lastKnownQuota = data.quota; }
            $('#cpab-quota').removeClass('is-idle is-error').addClass('is-ok').text(formatQuota(data.quota));
            handleQuotaNotice(data.quota);
            renderResolutionNote();
            var charged = Number(data.credits_charged) || genOptions.cost || 1;
            var chargedText = charged > 1 ? '，本次消耗 ' + charged + ' 次' : '';
            setButtonState($button, 'is-success', '出图成功，点击可再次生成');
            setStatus('楼层 ' + messageId + '：出图完成，seed=' + data.seed + '，steps=' + data.steps + chargedText);
            showToast('success', '图片已注入楼层，' + formatQuota(data.quota));
            setTimeout(function () {
                setButtonState($button, '', mode === 'random' ? '随机重绘' : (mode === 'optimize' ? '固定种子，步数 +2 优化（最高 8 步）' : '生成图片'));
            }, 2500);
        } finally {
            refreshQueueStatus(true).catch(function () {});
        }
    }

    async function handleGenerateClick(event, mode) {
        event.preventDefault();
        event.stopPropagation();
        var $button = $(event.currentTarget);
        var messageId = Number($button.attr('data-cpab-mesid'));
        try {
            await generateForMessage(messageId, $button, mode);
        } catch (error) {
            setButtonState($button, 'is-error', '生图失败，点击重试');
            setStatus('生图失败：' + (error.message || error));
            showToast('error', error.message || String(error));
            if (Number(error.status) === 402 || /次数已用完|卡密已过期/.test(String(error.message || ''))) {
                showPurchaseNotice(true);
            } else if (Number(error.status) === 403 && isIpLockedError(error.message)) {
                if (!ipLockedNoticeShown) { ipLockedNoticeShown = true; showIpLockedNotice(); }
            }
            refreshQuota(true).catch(function () {});
            refreshQueueStatus(true).catch(function () {});
        }
    }

