    /* 提交邀请码（补填场景） */
    async function applyInviteCode() {
        var apiUrl = resolveApiUrlForRequest();
        var apiKey = String(settings.apiKey || '').trim();
        if (!apiKey) {
            showToast('warning', '请先填写卡密，或点「领取免费50次」');
            return;
        }
        var code = normalizeInviteCode($('#cpab-invite-input').val());
        if (!code) {
            showToast('warning', '请先填写邀请码');
            return;
        }
        var $button = $('#cpab-apply-invite');
        $button.prop('disabled', true);
        try {
            var response = await fetch(apiUrl + '/v1/referral/apply', {
                method: 'POST',
                headers: { 'X-API-Key': apiKey, 'Content-Type': 'application/json' },
                body: JSON.stringify({ invite_code: code })
            });
            var data = await response.json();
            if (response.ok && data && data.ok === true) {
                showToast('success', data.message || '邀请码已生效');
                settings.pendingInviteCode = '';
                saveSettings();
                $('#cpab-invite-input').val('');
            } else {
                showToast('error', (data && (data.message || data.error)) || '邀请码处理失败');
            }
        } catch (error) {
            showToast('error', '邀请码提交失败：' + (error.message || error));
        } finally {
            $button.prop('disabled', false);
        }
    }

    /* 第二步：独立领邀请奖励（默认 30 次）。
       和领 50 次完全分开：失败了也不影响已经到账的 50 次。 */
    async function claimInviteBonus() {
        var code = normalizeInviteCode(settings.pendingInviteCode);
        if (!code) return null;
        var apiUrl = resolveApiUrlForRequest();
        var apiKey = String(settings.apiKey || '').trim();
        if (!apiKey) return null;
        try {
            var response = await fetch(apiUrl + '/v1/referral/apply', {
                method: 'POST',
                headers: { 'X-API-Key': apiKey, 'Content-Type': 'application/json' },
                body: JSON.stringify({ invite_code: code })
            });
            var data = await response.json();
            /* 不管成功失败，这个码都不再重复用 */
            settings.pendingInviteCode = '';
            saveSettings();
            if (response.ok && data && data.ok === true) {
                if (data.quota) {
                    setStatus('邀请奖励已到账');
                }
                showToast('success', data.message || '邀请奖励已到账');
                if (typeof refreshQuota === 'function') { try { await refreshQuota(true); } catch (e) {} }
                return data;
            }
            showToast('warning', (data && (data.message || data.error)) || '邀请奖励未计入');
            return null;
        } catch (error) {
            showToast('warning', '邀请奖励获取失败（不影响画图）：' + (error.message || error));
            return null;
        }
    }

