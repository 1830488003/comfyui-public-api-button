    async function refreshReferral(silent) {
        var apiUrl = resolveApiUrlForRequest();
        var apiKey = String(settings.apiKey || '').trim();
        if (!apiKey) {
            $('#cpab-invite-code').text('--------');
            $('#cpab-invite-link').text('填写卡密后这里会显示你的邀请链接');
            $('#cpab-invite-stat').text('');
            return null;
        }
        try {
            var response = await fetch(apiUrl + '/v1/referral', {
                method: 'GET',
                headers: { 'X-API-Key': apiKey, 'Content-Type': 'application/json' }
            });
            var data = await response.json();
            if (!response.ok || !data || data.ok === false || !data.referral) {
                throw new Error((data && data.error) || ('HTTP ' + response.status));
            }
            renderReferral(data.referral);
            return data.referral;
        } catch (error) {
            /* "Failed to fetch" 通常是网络到服务器这一段不通：
               刚重启服务时隧道要十几秒才建立连接，或者用户没开代理。
               这里给一句能指导动作的话，别让用户以为插件坏了。 */
            var reason = (error && error.message) ? error.message : String(error);
            if (/failed to fetch|networkerror|load failed/i.test(reason)) {
                reason = '连不上服务器（刚重启服务要等十几秒，或检查网络/代理），稍后点「刷新」重试';
            }
            $('#cpab-invite-link').text('邀请信息暂时取不到：' + reason);
            if (!silent) showToast('error', '邀请信息暂时取不到：' + reason);
            return null;
        }
    }

